// 工程定例の文字起こし（話し言葉のまま）。タイムスタンプは発言の長さから自動で振る。

function stamp(lines, { totalSec, startSec = 4 }) {
  const chars = lines.reduce((n, l) => n + l[1].length + 25, 0);
  const k = (totalSec - startSec) / chars;
  let t = startSec;
  return lines
    .map(([who, text]) => {
      const hh = String(Math.floor(t / 3600)).padStart(2, "0");
      const mm = String(Math.floor((t % 3600) / 60)).padStart(2, "0");
      const ss = String(Math.floor(t % 60)).padStart(2, "0");
      t += (text.length + 25) * k;
      return `[${hh}:${mm}:${ss}] ${who}：${text}`;
    })
    .join("\n\n");
}

